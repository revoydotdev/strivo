#!/usr/bin/env bash
# Per-plugin README generator. Synthesises one README.md per
# crates/<name>/ from that crate's Cargo.toml. Run from the repo root.
#
# Everything below the marker line is generated. Edit this script, never
# the output.
#
# Idempotent: re-runs overwrite the generated body but leave any
# hand-rolled file alone if it lacks the generated marker line.
set -euo pipefail
cd "$(dirname "$0")/.."

MARKER="<!-- generated by scripts/gen-plugin-readmes.sh; do not edit by hand -->"

# Dependency names that make a crate an integration surface rather than a
# pure-data transform. A crate depending on any of these must not claim
# to be "no IO" or "decoupled from ffmpeg, SQLite, IPC, HTTP" — those are
# exactly what it links. Deps absent from this table (serde, serde_json,
# anyhow, chrono, toml, semver, uuid) are value dependencies and do not
# contradict the pure-data description.
surface_label() {
  case "$1" in
    rusqlite)          echo "an embedded SQLite database" ;;
    sqlx)              echo "a SQL database" ;;
    tokio|tokio-util)  echo "the async runtime" ;;
    axum)              echo "an HTTP server" ;;
    hyper)             echo "an HTTP stack" ;;
    reqwest)           echo "an HTTP client" ;;
    ffmpeg)            echo "ffmpeg process control" ;;
    wry)               echo "an embedded webview" ;;
    clap)              echo "CLI argument parsing" ;;
    clap_complete)     echo "shell-completion generation" ;;
    clap_mangen)       echo "man-page generation" ;;
    which)             echo "external-executable discovery" ;;
    directories)       echo "OS config-path lookup" ;;
    tracing|tracing-subscriber) echo "logging" ;;
    *)                 return 1 ;;
  esac
}

# Names of a crate's [dependencies]. This approximates TOML: it takes the
# key of every `key = ...` line in the section, so a `foo.workspace = true`
# key yields `foo`. Keys must sit in column 0, which is what separates a
# real key from the continuation line of a multi-line inline table — an
# indented `features = [...]` is a value, not a dependency. It does not
# evaluate target-specific dependency tables.
crate_deps() {
  awk '/^[[:space:]]*\[dependencies\]/{f=1;next}
       /^[[:space:]]*\[/{f=0}
       f && /^[A-Za-z0-9_.-]+[[:space:]]*=/ {
         sub(/[[:space:]]*=.*$/, ""); sub(/\..*$/, "")
         print
       }' "$1"
}

# Crate metadata lookup via grep — keeps this script dep-free for CI.
for crate in crates/*/; do
  name="$(basename "$crate")"
  toml="${crate}Cargo.toml"
  [[ -f "$toml" ]] || continue
  desc="$(grep -m1 '^description' "$toml" | sed -E 's/^description = "(.*)"$/\1/')"
  pkg="$(grep -m1 '^name' "$toml" | sed -E 's/^name = "(.*)"$/\1/')"
  ver="$(grep -m1 '^version' "$toml" | sed -E 's/^version = "(.*)"$/\1/')"
  # strivo-bin/strivo-web inherit `version.workspace = true` from root
  # Cargo.toml's [workspace.package] rather than declaring their own.
  if [[ -z "$ver" ]]; then
    ver="$(grep -m1 '^version' Cargo.toml | sed -E 's/^version = "(.*)"$/\1/')"
  fi
  lic="$(grep -m1 '^license' "$toml" | sed -E 's/^license = "(.*)"$/\1/' || true)"
  # Unanchored on purpose: every #[test] in this tree sits indented inside
  # `mod tests`, so a `^#\[test\]` anchor never matches and reported 0 for
  # all 34 generated crates. Matches both #[test] and #[tokio::test]; the
  # two are mutually exclusive substrings, so no double count.
  ts=$(grep -rhoE '#\[(tokio::)?test\]' "${crate}src/" 2>/dev/null | wc -l || true)

  # Integration surface actually declared in [dependencies].
  declare -A seen=()
  surfaces=()
  while read -r dep; do
    if [[ "$dep" == strivo-* ]]; then
      label="the \`${dep}\` workspace crate"
    else
      label="$(surface_label "$dep")" || continue
    fi
    if [[ -z "${seen[$label]+x}" ]]; then
      seen[$label]=1
      surfaces+=("$label")
    fi
  done < <(crate_deps "$toml")

  if [[ ${#surfaces[@]} -gt 0 ]]; then
    joined="$(printf '%s, ' "${surfaces[@]}")"
    joined="${joined%, }"
    arch="\`${pkg}\` is not a pure-data crate. Its \`[dependencies]\` link it
directly to ${joined}. The list is read from \`Cargo.toml\`, so it tracks the
manifest rather than a hardcoded claim."
    rules="1. Expose typed models and functions that a caller — the host, a
   sibling plugin, or the CLI — can drive directly (see \`src/lib.rs\`).
2. Keep the integration points above in one place, so the remaining logic
   stays unit-testable without a live runtime."
  else
    arch="\`${pkg}\` is a pure-data Rust crate — no IO, no DOM. The host
(\`crates/strivo-web/\`) wires it to a Pro-gated HTTP endpoint and
surfaces the result on the SPA."
    rules="1. Provide typed model(s) that describe what the plugin produces or
   consumes (see \`src/lib.rs\` for the public surface).
2. Compose pure transformations on those models — filter builders,
   parsers, geometry, scoring, ranking — that can be unit-tested
   without any external runtime.
3. Stay decoupled from ffmpeg, SQLite, IPC, HTTP — those live in the
   host. The crate's signature surface is just types + functions
   over them."
  fi

  out="${crate}README.md"
  # Preserve hand-rolled READMEs unless they carry our marker.
  if [[ -f "$out" ]] && ! grep -qF "$MARKER" "$out"; then
    echo "skip (hand-rolled): $out"
    continue
  fi

  cat >"$out" <<EOF
# ${pkg}

${desc}

${MARKER}

| | |
|---|---|
| **Version** | \`${ver}\` |
| **License** | \`${lic}\` |
| **Unit tests** | ${ts} |
| **Source** | [\`crates/${name}/src/lib.rs\`](src/lib.rs) |

## Architecture

${arch}

The crate's responsibility is:

${rules}

## Testing

\`\`\`bash
cargo test -p ${pkg}
\`\`\`

## Capability tags

See the marketplace manifest in
\`crates/marketplace/src/lib.rs::default_catalog()\` for the
canonical capability tags this plugin produces / consumes and the
DAW-vision \`x.\`-prefixed extensions.
EOF
  echo "wrote: $out"
done

#!/usr/bin/env python3
"""Generate the redistributable media fixture corpus (plan todo 32, F10).

Every file is encoded from an ffmpeg `lavfi` *synthetic* source — no input
file, no downloaded media, no screen capture, nothing a person made. That is
the whole licence argument: the output of a tool, from a source the tool
generates, carries no third-party rights, and it ships under this repository's
own MIT licence like the script that made it.

This is NOT todo 9's `seed_bench_library.py`. That one seeds a throwaway
10 000-row *library* for a latency measurement and deletes it on exit; the
files exist only for the length of a benchmark run. This one writes a
committed corpus with a manifest, and every class is proven by `ffprobe`
rather than by the name it was given. `scripts/verify_media_fixtures.py`
holds the assertions; this file only produces bytes and records provenance.

Usage:
    scripts/seed_media_fixtures.py [out_dir]

Defaults to `fixtures/media`. The output directory is emptied of anything
this script owns before it runs, so a class removed from SPECS cannot linger
as a stale fixture, and each file is written to a temporary name and renamed
into place so an interrupted run cannot leave a half-written file that looks
complete to `git add`.
"""

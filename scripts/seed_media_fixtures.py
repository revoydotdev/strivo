# The shared encoder. A per-class `tail` overrides any of these, and because
# `tail` is appended afterwards ffmpeg's last-wins codec selection makes the
# override real. `-c:a aac` is here rather than per-class only so the default
# audio codec is explicit: ffmpeg's own default is vorbis, and a fixture whose
# audio codec is whatever the encoder felt like is a fixture whose properties
# move when ffmpeg's defaults do.
ENCODER = ["-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
           "-b:v", "64k", "-c:a", "aac", "-b:a", "64k"]


def encode(spec, out_dir):
    """Encode one fixture. Returns the absolute path."""
    dest = os.path.join(out_dir, spec["name"])
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    cmd = (["ffmpeg"] + COMMON + spec["args"] + ENCODER + BITEXACT
           + spec.get("tail", []) + [dest])
    # ffmpeg applies trailing options to the *next* output, so the output path
    # is the last argument by construction. That is exactly the trap todo 9
    # fell into: a codec override placed after the path was applied to a file
    # that was never written, leaving an h264 file labelled "mixed codec".
    subprocess.run(cmd, check=True, timeout=FFMPEG_TIMEOUT_S)
    return dest


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    out_dir = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    if not os.path.isdir(REPO_ROOT):
        print("seed_media_fixtures.py must be run from a StriVo checkout",
              file=sys.stderr)
        return 2
    if shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None:
        print("ffmpeg and ffprobe must both be on PATH", file=sys.stderr)
        return 2

    # Stale-state guard. A class deleted from SPECS must disappear rather than
    # linger as a fixture nothing regenerates, so every media file and every
    # subdirectory at the top of the corpus is cleared, not just the ones this
    # run happens to rewrite. The guard below is what makes that safe to do.
    os.makedirs(out_dir, exist_ok=True)
    if os.path.abspath(out_dir) == REPO_ROOT or os.path.exists(
            os.path.join(out_dir, ".git")):
        print(f"refusing to prune {out_dir}: it looks like a checkout root, "
              "not a corpus directory", file=sys.stderr)
        return 2

    # Order matters, and getting it wrong is a real bug this script's own
    # interrupt probe found once: prune FIRST and a run killed during encoding
    # leaves the corpus with files simply deleted, because the replacements
    # did not exist yet. So the new corpus is built in full, in a staging
    # directory, before anything in the corpus is removed.
    staging = tempfile.mkdtemp(prefix=".staging-", dir=out_dir)
    try:
        built = []
        for spec in SPECS:
            built.append((spec, encode(spec, staging)))

        # Stale-state prune, now that the replacements exist. A class deleted
        # from SPECS disappears instead of lingering as a fixture nothing
        # regenerates. Non-media files are never touched.
        keep = {os.path.normpath(s["name"]) for s, _ in built}
        for entry in os.listdir(out_dir):
            if entry.startswith("."):
                continue
            target = os.path.join(out_dir, entry)
            if os.path.normpath(entry) in keep:
                continue
            if os.path.isdir(target):
                shutil.rmtree(target)
            elif os.path.splitext(entry)[1].lower() in MEDIA_EXTENSIONS:
                os.remove(target)

        entries = []
        for spec, staged in built:
            final = os.path.join(out_dir, spec["name"])
            os.makedirs(os.path.dirname(final), exist_ok=True)
            # os.replace is atomic within a filesystem, which is what staging
            # inside out_dir buys. The manifest below is written last and is
            # the commit point: a run killed between two replaces leaves bytes
            # the manifest does not describe, and the verifier fails on that
            # rather than passing over it.
            os.replace(staged, final)
            entries.append({
                "name": spec["name"],
                "class": spec["class"],
                "bytes": os.path.getsize(final),
                "sha256": sha256(final),
                "provenance": spec["provenance"],
                "license": spec["license"],
            })
    finally:
        shutil.rmtree(staging, ignore_errors=True)

    manifest_path = os.path.join(out_dir, "MANIFEST.json")
    manifest = {
        "note": ("ffprobe-verified by scripts/verify_media_fixtures.py. The "
                 "`class` field is a claim; the `ffprobe` block in the same "
                 "entry is the evidence for it."),
        "ffmpeg_version": subprocess.run(
            ["ffmpeg", "-version"], capture_output=True, text=True,
            check=True).stdout.splitlines()[0],
        "size_budget_bytes": 1536 * 1024,
        "fixtures": entries,
    }
    tmp = manifest_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    os.replace(tmp, manifest_path)
    total = sum(e["bytes"] for e in entries)
    print(f"{len(entries)} fixtures, {total} bytes, manifest -> {manifest_path}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
